package main

// benchmark_authority_test.go — guard for the benchmark-file authority
// resolution (SOC #18, v2.4.0; see docs/BENCHMARKS.md).
//
// History: benchmark/detect_results.json (aegis FP=60, any-finding
// standard, pre-FP-fix binary) contradicted benchmark/heldout_results.json
// and the live gate (FP=0, medium+ standard). The two files used different
// measurement standards and different binaries, and neither recorded its
// standard or provenance — so the contradiction sat undetected from
// 2026-10-12 until the v2.4.0 audit.
//
// The fix: ONE standard (medium+ only; low/info hygiene excluded, exactly
// as the live quality gate counts it) and ONE stored authority per corpus
// (benchmark/heldout_results.json for the phase-5 held-out set,
// benchmark/rigorous/heldout2_results.json for the rigorous set), each
// regenerated by its script with a _meta provenance block.
//
// These tests make the contradiction unrepeatable:
//  1. The deleted stale files must stay deleted.
//  2. Each authority file's aegis block must match a fresh in-process scan
//     of its corpus with the CURRENT build, using the CLI's own scan path
//     (scanFull) and the gate's medium+ counting. If a rule change moves
//     the numbers, the file must be regenerated (benchmark/run_heldout.py,
//     benchmark/rigorous/heldout2_run.py) — not hand-edited — or this test
//     fails loudly instead of the repo silently carrying stale numbers.
//
// The tests skip when a corpus directory is absent (e.g. sparse checkout);
// they fail when the corpus is present but the numbers disagree.

import (
	"encoding/json"
	"os"
	"path/filepath"
	"testing"

	"aegis/internal/ir"
	"aegis/internal/rules"
)

const benchmarkRoot = "../../benchmark"

// isActionable mirrors internal/qualitygate benchStats: medium and above
// count; low/info hygiene findings are informational and excluded.
func isActionable(s ir.Severity) bool {
	return s != ir.SeverityLow && s != ir.SeverityInfo
}

type benchManifestEntry struct {
	Project    string `json:"project"`
	Vulnerable bool   `json:"vulnerable"`
}

type benchResultsFile struct {
	Aegis struct {
		TP     int `json:"tp"`
		FP     int `json:"fp"`
		FN     int `json:"fn"`
		TN     int `json:"tn"`
		Errors int `json:"errors"`
	} `json:"aegis"`
}

// TestBenchmarkStaleFilesAbsent guards the deletions: the pre-fix snapshots
// whose numbers contradicted the live gate must not come back.
func TestBenchmarkStaleFilesAbsent(t *testing.T) {
	for _, stale := range []string{
		"detect_results.json",
		"heldout_severity_results.json",
	} {
		p := filepath.Join(benchmarkRoot, stale)
		if _, err := os.Stat(p); err == nil {
			t.Errorf("stale benchmark file %s exists again — it was deleted "+
				"as a pre-FP-fix snapshot that contradicted the live gate "+
				"(see docs/BENCHMARKS.md); do not restore it, regenerate "+
				"benchmark/heldout_results.json instead", p)
		} else if !os.IsNotExist(err) {
			t.Fatalf("stat %s: %v", p, err)
		}
	}
}

// scanCorpusMediumPlus scans every project in manifest with the CLI scan
// path and returns project-level confusion counts on the medium+ standard.
func scanCorpusMediumPlus(t *testing.T, corpusDir string, manifestPath string) (tp, fp, fn, tn, errors int) {
	t.Helper()
	data, err := os.ReadFile(manifestPath)
	if err != nil {
		t.Fatalf("read manifest %s: %v", manifestPath, err)
	}
	var manifest []benchManifestEntry
	if err := json.Unmarshal(data, &manifest); err != nil {
		t.Fatalf("parse manifest %s: %v", manifestPath, err)
	}
	registry := rules.DefaultRegistry()
	for _, m := range manifest {
		res, _, _, err := scanFull(filepath.Join(corpusDir, m.Project), defaultAdapters(), registry)
		if err != nil {
			errors++
			continue
		}
		found := false
		for _, f := range res.Findings {
			if isActionable(f.Severity) {
				found = true
				break
			}
		}
		switch {
		case m.Vulnerable && found:
			tp++
		case m.Vulnerable && !found:
			fn++
		case !m.Vulnerable && found:
			fp++
		default:
			tn++
		}
	}
	return tp, fp, fn, tn, errors
}

func checkAuthorityFile(t *testing.T, name, corpusDir, manifestPath, resultsPath string) {
	t.Helper()
	if _, err := os.Stat(corpusDir); err != nil {
		if os.IsNotExist(err) {
			t.Skipf("corpus %s absent, skipping", corpusDir)
		}
		t.Fatalf("stat %s: %v", corpusDir, err)
	}
	data, err := os.ReadFile(resultsPath)
	if err != nil {
		t.Fatalf("read %s: %v", resultsPath, err)
	}
	var stored benchResultsFile
	if err := json.Unmarshal(data, &stored); err != nil {
		t.Fatalf("parse %s: %v", resultsPath, err)
	}
	tp, fp, fn, tn, errors := scanCorpusMediumPlus(t, corpusDir, manifestPath)
	a := stored.Aegis
	if tp != a.TP || fp != a.FP || fn != a.FN || tn != a.TN || errors != a.Errors {
		t.Errorf("%s aegis block is stale: file claims TP=%d FP=%d FN=%d TN=%d errors=%d, "+
			"but a fresh scan of %s with the current build gives TP=%d FP=%d FN=%d TN=%d errors=%d. "+
			"Regenerate it with its script (see docs/BENCHMARKS.md); do not hand-edit the numbers.",
			name, a.TP, a.FP, a.FN, a.TN, a.Errors,
			corpusDir, tp, fp, fn, tn, errors)
	}
}

func TestHeldoutResultsMatchCurrentBuild(t *testing.T) {
	checkAuthorityFile(t, "benchmark/heldout_results.json",
		filepath.Join(benchmarkRoot, "heldout"),
		filepath.Join(benchmarkRoot, "heldout_manifest.json"),
		filepath.Join(benchmarkRoot, "heldout_results.json"))
}

func TestHeldout2ResultsMatchCurrentBuild(t *testing.T) {
	checkAuthorityFile(t, "benchmark/rigorous/heldout2_results.json",
		filepath.Join(benchmarkRoot, "rigorous", "heldout2"),
		filepath.Join(benchmarkRoot, "rigorous", "heldout2_manifest.json"),
		filepath.Join(benchmarkRoot, "rigorous", "heldout2_results.json"))
}
