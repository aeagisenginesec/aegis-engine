package report

import (
	"fmt"
	"html"
	"io"
	"sort"
	"strings"

	"aegis/internal/ir"
)

// WriteHTML renders a standalone attestation report: a single
// self-contained HTML page (inline CSS, no external assets) carrying
// the scan's compliance posture per framework and the full findings
// table. It is designed to be filed as audit evidence — the output is
// deterministic for a given scan (no timestamps or random ordering),
// and secret values are redacted exactly as in the JSON report.
func WriteHTML(w io.Writer, res ir.ScanResult) error {
	findings := redactFindings(res.Findings)
	summaries := res.ComplianceSummaries
	if res.ComplianceSummary != nil {
		summaries = append([]*ir.ComplianceSummary{res.ComplianceSummary}, summaries...)
	}
	counts := summarize(res)

	var b strings.Builder
	b.WriteString("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
	fmt.Fprintf(&b, "<title>Aegis Compliance Attestation — %s</title>\n", html.EscapeString(res.Target))
	b.WriteString(`<style>
body{font-family:-apple-system,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;margin:2rem auto;max-width:960px;padding:0 1rem;color:#1a1d26;background:#fff}
header{border-bottom:3px solid #7c3aed;padding-bottom:1rem;margin-bottom:1.5rem}
h1{margin:0 0 .25rem;font-size:1.6rem}
h2{margin:2rem 0 .5rem;font-size:1.15rem}
.sub{color:#5b6172;font-size:.9rem}
table{border-collapse:collapse;width:100%;margin:.5rem 0 1rem;font-size:.88rem}
th,td{border:1px solid #d6d9e0;padding:.4rem .55rem;text-align:left;vertical-align:top}
th{background:#f1eefc}
tr.fail td{background:#fdf1f1}
.pass{color:#137333;font-weight:600}
.fail{color:#b3261e;font-weight:600}
.sev-critical{color:#b3261e;font-weight:700}
.sev-high{color:#d35400;font-weight:700}
.sev-medium{color:#8a6d00;font-weight:600}
.sev-low{color:#5b6172;font-weight:600}
code{font-family:ui-monospace,SFMono-Regular,Menlo,monospace;font-size:.82rem}
footer{margin-top:2.5rem;border-top:1px solid #d6d9e0;padding-top:.75rem;color:#5b6172;font-size:.8rem}
@media print{body{margin:0}}
</style>
</head>
<body>
<header>
<h1>Aegis Compliance Attestation</h1>
`)
	fmt.Fprintf(&b, "<div class=\"sub\">Target: <code>%s</code> · Aegis %s · %d resources scanned · %d files parsed</div>\n",
		html.EscapeString(res.Target), html.EscapeString(Version), res.Resources, res.Completeness.FilesParsed)
	fmt.Fprintf(&b, "<div class=\"sub\">Findings: %d (critical %d · high %d · medium %d · low %d)</div>\n</header>\n",
		counts.Findings, counts.Critical, counts.High, counts.Medium, counts.Low)

	if len(summaries) > 0 {
		b.WriteString("<h2>Compliance posture</h2>\n<table>\n<tr><th>Framework</th><th>Controls evaluated</th><th>Passing</th><th>Failing</th><th>Failed controls</th></tr>\n")
		for _, cs := range summaries {
			rowClass := ""
			status := "<span class=\"pass\">PASS</span>"
			if cs.ControlsFailing > 0 {
				rowClass = " class=\"fail\""
				status = "<span class=\"fail\">FAIL</span>"
			}
			fmt.Fprintf(&b, "<tr%s><td>%s %s</td><td>%d</td><td>%d</td><td>%d</td><td><code>%s</code></td></tr>\n",
				rowClass, html.EscapeString(cs.Framework), status,
				cs.ControlsTotal, cs.ControlsPassing, cs.ControlsFailing,
				html.EscapeString(strings.Join(cs.FailedControls, ", ")))
		}
		b.WriteString("</table>\n")
	}

	b.WriteString("<h2>Findings</h2>\n")
	if len(findings) == 0 {
		b.WriteString("<p>No findings.</p>\n")
	} else {
		sorted := make([]ir.Finding, len(findings))
		copy(sorted, findings)
		sort.SliceStable(sorted, func(i, j int) bool {
			if sorted[i].Severity != sorted[j].Severity {
				return severityRank(sorted[i].Severity) > severityRank(sorted[j].Severity)
			}
			return sorted[i].RuleID < sorted[j].RuleID
		})
		b.WriteString("<table>\n<tr><th>Severity</th><th>Rule</th><th>Finding</th><th>Location</th><th>Resource</th><th>Compliance</th></tr>\n")
		for _, f := range sorted {
			loc := f.Evidence.Span.File
			if loc != "" && f.Evidence.Span.StartLine > 0 {
				loc = fmt.Sprintf("%s:%d", loc, f.Evidence.Span.StartLine)
			}
			refs := make([]string, 0, len(f.Compliance))
			for _, r := range f.Compliance {
				refs = append(refs, r.Framework+" "+r.Control)
			}
			fmt.Fprintf(&b, "<tr><td class=\"sev-%s\">%s</td><td><code>%s</code></td><td>%s</td><td><code>%s</code></td><td><code>%s</code></td><td>%s</td></tr>\n",
				html.EscapeString(string(f.Severity)), html.EscapeString(string(f.Severity)),
				html.EscapeString(f.RuleID), html.EscapeString(f.Title),
				html.EscapeString(loc), html.EscapeString(f.Resource),
				html.EscapeString(strings.Join(refs, "; ")))
		}
		b.WriteString("</table>\n")
	}

	b.WriteString("<footer>Generated by Aegis — deterministic output: re-running this scan on the same tree reproduces this report byte-for-byte (modulo this page's formatting). A control is listed as failing when at least one finding maps to it; controls evaluated are all controls mapped in the Aegis ruleset for that framework.</footer>\n</body>\n</html>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

// severityRank orders severities for presentation (critical first).
func severityRank(s ir.Severity) int {
	switch s {
	case ir.SeverityCritical:
		return 4
	case ir.SeverityHigh:
		return 3
	case ir.SeverityMedium:
		return 2
	case ir.SeverityLow:
		return 1
	}
	return 0
}
